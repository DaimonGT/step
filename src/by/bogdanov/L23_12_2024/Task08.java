// вложенный for
public class Task08 {
    public static void main(String[] args) {
        for (int i = 0; i < 10; i++) {
            for (int j = 0; j < 10; j++) {
                System.out.println("переменная i " + i);
                System.out.println("переменная j " + j);
                System.out.println("--------------");
            }

        }
    }
}
