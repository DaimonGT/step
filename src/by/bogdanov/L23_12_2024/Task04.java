// Цикл for (инициализация; условие; инримент/дикремент)
import java.util.Scanner;

public class Task04 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int a = sc.nextInt();
        for (int i = 0; i < a; i++) {
            System.out.println("--------");
            System.out.println(i);
            System.out.println(a);
            System.out.println("--------");
            System.out.println("--------");
        }
    }
}
